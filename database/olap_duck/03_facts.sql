CREATE TABLE "fact_transactions" (
  "transaction_id" VARCHAR PRIMARY KEY,
  "related_transaction_id" VARCHAR REFERENCES fact_transactions(transaction_id),
  "card_id" VARCHAR NOT NULL REFERENCES cards(card_id),
  "produto_id" VARCHAR NOT NULL REFERENCES dim_produtos(produto_id),
  "establishment_id" VARCHAR NOT NULL REFERENCES establishments(establishment_id),
  "terminal_id" VARCHAR NOT NULL REFERENCES dim_terminais(terminal_id),
  "tecnologia_captura_id" VARCHAR NOT NULL REFERENCES dim_tecnologias_captura(tecnologia_id),
  "motivo_negacao_id" VARCHAR REFERENCES dim_motivos_negacao(motivo_negacao_id),
  "data_transacao" VARCHAR NOT NULL REFERENCES dim_data(data_id),
  "hora_transacao" time,
  "data_efetiva_transacao" date,
  "data_captura" timestamp,
  "nsu_transacao" varchar,
  "nsu_autorizacao" varchar,
  "codigo_tipo_transacao" varchar,
  "valor_transacao" decimal(18,2),
  "valor_comissao" decimal(18,2),
  "codigo_moeda" varchar,
  "descricao_transacao" varchar,
  "origem_transacao" varchar,
  "codigo_rede_captura" varchar,
  "codigo_processamento" varchar,
  "status_transacao" varchar,
  "tipo_transacao" varchar,
  "requer_liquidacao_bandeira" boolean,
  "data_liquidacao" date,
  "status_liquidacao" varchar,
  "created_at" timestamp
);